"""Procedural textures.

The renderer is only useful if what it produces has features in it.  A shaded
but untextured bracket gives a handful of corners and nothing for a descriptor
to match, so every surface here carries a multi-octave value noise with energy
at the scales SIFT looks at.  That is a stand-in for real surface detail, and
it is an easy one: real parts are often shiny, often nearly untextured, and the
README says so rather than pretending the synthetic case is the hard case.

The calibration board is not procedural.  It is generated by OpenCV's own
ChArUco code and detected by OpenCV's own detector, so the calibration path
exercises the same board handling a real rig would.
"""

from __future__ import annotations

import cv2
import numpy as np

#: The ChArUco dictionary used throughout.  4x4 is the smallest that still
#: decodes reliably at the resolution the renderer produces, which keeps the
#: markers large relative to the squares.
ARUCO_DICT = cv2.aruco.DICT_4X4_50


def spectral_noise(shape, rng, beta=1.5, f_min=2.0, f_max=None):
    """Noise with a ``1/f**beta`` power spectrum, generated in the Fourier domain.

    Two properties are bought by doing this spectrally rather than by summing
    resized grids of random values.

    **It tiles exactly.**  An inverse FFT is periodic by construction, so a
    surface whose texture coordinates wrap has no seam.  The earlier
    resize-and-sum generator did not tile, and the seams showed up in the
    renders as long straight intensity steps -- which the corner detector
    happily found, and which then matched between views because they were
    genuinely repeatable image structure that corresponded to no geometry at
    all.  That is the worst kind of synthetic artefact: it inflates the match
    count and biases the reconstruction.

    **The spectrum is a parameter.**  ``beta`` near 2 gives smooth mottling;
    near 1 it gives detail down to the pixel.  Feature density is a direct
    consequence, so it is a dial rather than an accident.
    """
    h, w = shape
    white = rng.standard_normal((h, w))
    spectrum = np.fft.rfft2(white)

    fy = np.fft.fftfreq(h)[:, None]
    fx = np.fft.rfftfreq(w)[None, :]
    radius = np.sqrt(fy * fy + fx * fx) * max(h, w)
    radius[0, 0] = 1.0

    amp = np.power(radius, -0.5 * beta)
    amp[radius < f_min] = 0.0          # kill the near-DC tilt
    if f_max is not None:
        amp[radius > f_max] = 0.0
    amp[0, 0] = 0.0

    out = np.fft.irfft2(spectrum * amp, s=(h, w))
    out -= out.mean()
    # Scale by the standard deviation rather than the range: one extreme
    # outlier pixel would otherwise squash the whole texture into a narrow band.
    out /= max(float(out.std()), 1e-12)
    return out.astype(np.float32)


def surface_texture(rng, size=1024, contrast=0.55, brightness=0.5, grain=0.05, beta=1.5):
    """A rough surface: broadband detail plus pixel-scale grain.

    ``grain`` is white noise, which tiles trivially, and is what keeps features
    available at the smallest scale the detector looks at.  Clipping at the end
    costs a little of the tail and is what a real sensor does too.
    """
    base = spectral_noise((size, size), rng, beta=beta)
    tex = brightness + contrast * 0.34 * base
    tex += grain * rng.standard_normal((size, size)).astype(np.float32)
    return np.clip(tex, 0.02, 0.98).astype(np.float32)


def machined_texture(rng, size=1024):
    """As :func:`surface_texture` but with a directional tool-mark component.

    The tool marks run along one axis with a period that divides ``size``, so
    they stay periodic and the texture still tiles.
    """
    tex = surface_texture(rng, size, contrast=0.95, brightness=0.62, grain=0.055, beta=1.3)
    period = 16
    x = np.arange(size, dtype=np.float32)
    lines = 0.5 + 0.5 * np.sin(x * (2.0 * np.pi / period) + float(rng.random()) * 6.283)
    tex = np.clip(tex * (0.90 + 0.10 * lines[None, :]), 0.02, 0.98)
    return tex.astype(np.float32)


def charuco_board(squares_x=7, squares_y=5, square_length=0.040, marker_ratio=0.75):
    """The calibration board object and its metric geometry.

    ``square_length`` is in metres and is the one number that sets the scale of
    everything downstream: a rig calibrated against a board whose squares are
    not the size you think they are produces a reconstruction that is
    self-consistent and the wrong size.
    """
    dictionary = cv2.aruco.getPredefinedDictionary(ARUCO_DICT)
    board = cv2.aruco.CharucoBoard(
        (squares_x, squares_y), float(square_length), float(square_length * marker_ratio),
        dictionary,
    )
    # Legacy pattern off: the modern layout puts a marker in the top-left
    # square, which is what CharucoDetector expects by default.
    board.setLegacyPattern(False)
    return board


def charuco_texture(board, px_per_square=140, margin_squares=0.35):
    """Render the board to a greyscale image, with a quiet margin around it.

    The margin is white board material, not scene: the detector needs a light
    quiet zone around the outer markers, and rendering the board flush to the
    edge of the plane makes detection fail at oblique angles for reasons that
    look like a calibration bug and are not.
    """
    nx, ny = board.getChessboardSize()
    inner = (int(nx * px_per_square), int(ny * px_per_square))
    margin_px = int(round(margin_squares * px_per_square))
    img = board.generateImage((inner[0], inner[1]), marginSize=0)
    canvas = np.full(
        (inner[1] + 2 * margin_px, inner[0] + 2 * margin_px), 255, dtype=np.uint8
    )
    canvas[margin_px:margin_px + inner[1], margin_px:margin_px + inner[0]] = img
    # The quad the texture is mapped onto covers the whole canvas, so the
    # caller needs the margin in metres to build it.
    margin_m = float(margin_squares * board.getSquareLength())
    return (canvas.astype(np.float32) / 255.0), margin_m


def sample_bilinear(texture, uv):
    """Bilinear texture lookup with wrapping, for ``(N, 2)`` texture coordinates.

    Wrapping rather than clamping is what lets :func:`_planar_uv` hand out
    unbounded world-scaled coordinates and get a tiled surface back.
    """
    h, w = texture.shape[:2]
    u = np.mod(uv[:, 0], 1.0) * (w - 1)
    v = np.mod(uv[:, 1], 1.0) * (h - 1)
    x0 = np.floor(u).astype(np.int32)
    y0 = np.floor(v).astype(np.int32)
    x1 = np.minimum(x0 + 1, w - 1)
    y1 = np.minimum(y0 + 1, h - 1)
    fx = (u - x0)[:, None] if texture.ndim == 3 else (u - x0)
    fy = (v - y0)[:, None] if texture.ndim == 3 else (v - y0)
    top = texture[y0, x0] * (1 - fx) + texture[y0, x1] * fx
    bot = texture[y1, x0] * (1 - fx) + texture[y1, x1] * fx
    return top * (1 - fy) + bot * fy
