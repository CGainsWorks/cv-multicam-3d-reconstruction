"""Training loop for the pose-refinement network.

Nothing exotic: AdamW, a cosine schedule, gradient clipping, and the
point-matching loss from :mod:`multicam.pose.network`.  What is worth stating
is what is *held out*.

* The test split of the pose session is never loaded here.  It is selected by a
  fixed rule -- the last N stations -- in :meth:`Dataset.pose_split`, so no
  seed or shuffle can leak it.
* A validation split is carved from the *training* stations, by station, not by
  sample.  Splitting by sample would put different perturbations of the same
  capture on both sides and the validation loss would be meaningless.

The training data is generated by perturbing known poses, so an epoch is as
large as you want it to be; ``samples_per_frame`` sets it.  More samples per
station is more perturbations of the same images, which helps up to a point and
then stops.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field

import numpy as np

from ..geometry import se3
from .dataset import RefinementDataset, collate
from .network import PoseRefineNet, describe, point_matching_loss


@dataclass
class TrainConfig:
    epochs: int = 24
    batch_size: int = 16
    samples_per_frame: int = 10
    learning_rate: float = 3e-4
    weight_decay: float = 1e-4
    grad_clip: float = 1.0
    validation_fraction: float = 0.15
    model_points: int = 512
    num_workers: int = 0
    width: int = 32
    seed: int = 0
    device: str = "auto"


@dataclass
class TrainResult:
    state_dict: dict = None
    history: list = field(default_factory=list)
    best_validation: float = float("inf")
    seconds: float = 0.0
    config: dict = field(default_factory=dict)
    stats: dict = field(default_factory=dict)


def resolve_device(name="auto"):
    import torch

    if name != "auto":
        return name
    return "cuda" if torch.cuda.is_available() else "cpu"


def train(images_by_frame, poses_by_frame, rig, renderer, cad, config=None,
          perturbation=None, progress=None):
    """Train a refiner and return the best checkpoint by validation loss."""
    import torch
    from torch.utils.data import DataLoader

    config = config or TrainConfig()
    device = resolve_device(config.device)
    rng = np.random.default_rng(config.seed)

    frames = sorted(images_by_frame)
    n_val = max(1, int(round(len(frames) * config.validation_fraction)))
    # Split by station, deterministically, and record which went where.
    order = list(rng.permutation(len(frames)))
    val_frames = sorted(frames[i] for i in order[:n_val])
    train_frames = sorted(frames[i] for i in order[n_val:])

    model_points, _ = cad.sample_surface(int(config.model_points), rng)
    model_points_t = torch.from_numpy(model_points.astype(np.float32)).to(device)

    def make(frames_subset, samples, seed):
        return RefinementDataset(
            {f: images_by_frame[f] for f in frames_subset},
            {f: poses_by_frame[f] for f in frames_subset},
            rig, renderer, model_points,
            perturbation=perturbation, samples_per_frame=samples, seed=seed,
        )

    train_set = make(train_frames, config.samples_per_frame, config.seed + 1)
    val_set = make(val_frames, max(4, config.samples_per_frame // 2), config.seed + 999)

    train_loader = DataLoader(
        train_set, batch_size=config.batch_size, shuffle=True, collate_fn=collate,
        num_workers=config.num_workers, drop_last=True,
    )
    val_loader = DataLoader(
        val_set, batch_size=config.batch_size, shuffle=False, collate_fn=collate,
        num_workers=0,
    )

    net = PoseRefineNet(n_cameras=rig.n_cameras, width=config.width).to(device)
    optimiser = torch.optim.AdamW(
        net.parameters(), lr=config.learning_rate, weight_decay=config.weight_decay
    )
    steps = max(1, len(train_loader) * config.epochs)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimiser, T_max=steps)

    best_state, best_val = None, float("inf")
    history = []
    t0 = time.time()

    for epoch in range(config.epochs):
        net.train()
        losses = []
        for batch in train_loader:
            crops = batch["crops"].to(device)
            valid = batch["valid"].to(device)
            T_current = batch["T_current"].to(device)
            T_target = batch["T_target"].to(device)

            twist = net(crops, valid)
            loss = point_matching_loss(twist, T_current, T_target, model_points_t)

            optimiser.zero_grad(set_to_none=True)
            loss.backward()
            if config.grad_clip:
                torch.nn.utils.clip_grad_norm_(net.parameters(), config.grad_clip)
            optimiser.step()
            scheduler.step()
            losses.append(float(loss.detach().cpu()))

        net.eval()
        val_losses, baseline = [], []
        with torch.no_grad():
            for batch in val_loader:
                crops = batch["crops"].to(device)
                valid = batch["valid"].to(device)
                T_current = batch["T_current"].to(device)
                T_target = batch["T_target"].to(device)
                twist = net(crops, valid)
                val_losses.append(float(
                    point_matching_loss(twist, T_current, T_target, model_points_t)
                ))
                # What the loss would be if the network predicted nothing.  The
                # ratio to it is the only number that says the refiner is doing
                # anything at all.
                zero = torch.zeros_like(twist)
                baseline.append(float(
                    point_matching_loss(zero, T_current, T_target, model_points_t)
                ))

        train_loss = float(np.mean(losses)) if losses else float("nan")
        val_loss = float(np.mean(val_losses)) if val_losses else float("nan")
        base_loss = float(np.mean(baseline)) if baseline else float("nan")
        history.append({
            "epoch": epoch,
            "train_mm": train_loss * 1000.0,
            "val_mm": val_loss * 1000.0,
            "identity_mm": base_loss * 1000.0,
            "improvement": (base_loss - val_loss) / max(base_loss, 1e-12),
            "lr": float(scheduler.get_last_lr()[0]),
        })
        if progress:
            progress(history[-1])
        if val_loss < best_val:
            best_val = val_loss
            best_state = {k: v.detach().cpu().clone() for k, v in net.state_dict().items()}

    return TrainResult(
        state_dict=best_state,
        history=history,
        best_validation=best_val,
        seconds=time.time() - t0,
        config={
            "epochs": config.epochs,
            "batch_size": config.batch_size,
            "samples_per_frame": config.samples_per_frame,
            "learning_rate": config.learning_rate,
            "weight_decay": config.weight_decay,
            "model_points": config.model_points,
            "width": config.width,
            "seed": config.seed,
            "device": device,
            "in_channels": 4,
            "n_cameras": rig.n_cameras,
            "crop": renderer.crop,
            "perturbation": (perturbation or train_set.perturbation).describe(),
        },
        stats={
            "train_stations": train_frames,
            "validation_stations": val_frames,
            "train_samples": len(train_set),
            "validation_samples": len(val_set),
            "network": describe(net),
        },
    )


def measure_classical_errors(estimates, truths):
    """The error distribution of a set of classical estimates.

    Used to justify the perturbation range rather than guessing it.  Returns
    percentiles of translation and rotation error.
    """
    trans, rot = [], []
    for T_est, T_true in zip(estimates, truths):
        if T_est is None:
            continue
        t, r = se3.pose_error(T_est, T_true)
        trans.append(t)
        rot.append(r)
    if not trans:
        return {}
    return {
        "n": len(trans),
        "translation_mm": {
            "median": float(np.median(trans)) * 1000,
            "p90": float(np.quantile(trans, 0.9)) * 1000,
            "max": float(np.max(trans)) * 1000,
        },
        "rotation_deg": {
            "median": float(np.median(rot)),
            "p90": float(np.quantile(rot, 0.9)),
            "max": float(np.max(rot)),
        },
    }
